"""The ops store ports."""
from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol

from docai.schemas.rows import DocumentRow, Dossier, FileRow, OutboxRow, PageRow, RegisterResult


class ReviewOps(Protocol):
    """Part of the OpsStore: review claims, decisions and demand (one transaction each, in adapters/sql/ops.py)."""

    def set_departments(self, departments: list[str]) -> None:
        """Tells the store which departments the caller may see. Row-level security on review tasks reads it (the transaction-local
        setting app.departments); it must be set before every call that touches review tasks, because connections are reused."""
    def claim_task(self, user_oid: str, departments: list[str], *, lease_minutes: int = 15, escalate_after: int = 3,
                oldest_every: int = 5, window_days: int = 30, from_status: str = "open") -> dict[str, Any] | None:
        """`from_status='escalated'` is how a steward takes an escalated task."""
    def renew_lease(self, task_id: int, lease_token: str, lease_minutes: int = 15) -> datetime | None: ...
    def get_task(self, task_id: int) -> dict[str, Any]: ...
    def decide_task(self, task_id: int, lease_token: str, decision: str, decided_by: str, payload: dict[str, Any]) -> str:
        """Closes the task and queues review.decided in one transaction. Raises LeaseLost."""
    def apply_decision(self, task_id: int, document_id: str) -> tuple[int, bool]:
        """(version, repeated). The version rises once per task; a redelivery gets the stored version back."""
    def applied_tasks(self, document_id: str) -> dict[int, int]: ...
    def record_demand(self, hits: list[dict[str, str]], answer_id: str | None = None) -> None: ...
    def supersede_older_revisions(self, dossier_id: str, revision: int) -> list[str]: ...
    def enqueue(self, message_id: str, destination: str, body: str, session_id: str | None = None) -> bool: ...
    def change_dossier_acl(self, dossier_id: str, new_acl: list[str], changed_by: str, reason: str, widened: bool = False) -> int:
        """Audits the change and queues one index message per document and one hint message, atomically. Returns the new acl_version."""
    def upsert_content_flag(self, chunk_id: str, document_id: str, department: str, source: str) -> None: ...
    def save_turn(self, *, answer_id: str, conversation_id: str, user_oid: str, question: str, answer: str, abstained: bool,
                abstain_reason: str | None, intent: str | None, language: str | None, evidence: list[dict[str, Any]], verdict: dict[str, Any] | None,
                scope_hash: str, latency_ms: int) -> int:
        """Stores one exchange and returns its turn number in the conversation."""
    def history(self, conversation_id: str, user_oid: str, limit: int = 3) -> list[dict[str, Any]]: ...
    def purge_conversations(self, older_than_days: int) -> int: ...

    # hints
    def submit_hint(self, *, department: str, type: str, language: str, text: str, author_oid: str, author_name: str = "",
                    terms: list[str] | None = None, scope_level: str = "department", scope_dossier_ids: list[str] | None = None,
                    evidence: list[dict[str, Any]] | None = None, evidence_status: str = "documentary", from_answer: str | None = None,
                    target_line_key: str | None = None, suggested_text: str | None = None) -> str:
        """Writes the hint and its outbox row in one transaction. Returns the hint ID."""
    def get_hint(self, hint_id: str) -> dict[str, Any]: ...
    def list_hints(self, department: str | None = None, status: str | None = None, type: str | None = None) -> list[dict[str, Any]]: ...
    def set_hint_status(self, hint_id: str, new_status: str, expected_row_version: int, *, actor_oid: str | None = None,
                        actor_name: str | None = None, reason: str | None = None, check_results: dict[str, Any] | None = None,
                        acl_groups: list[str] | None = None) -> int:
        """Enforces the transitions, the four-eyes rule and optimistic concurrency. Returns the new row_version."""
    def edit_hint(self, hint_id: str, expected_row_version: int, text: str, editor_name: str) -> int: ...
    def record_publication(self, hint_id: str, destination: str, action: str, reason: str = "approval") -> None: ...
    def record_acl_audit(self, *, hint_id: str | None = None, dossier_id: str | None = None, changed_by: str, reason: str,
                        old_acl: list[str], new_acl: list[str], widened: bool) -> None: ...
    def hints_anchored_to(self, dossier_id: str) -> list[dict[str, Any]]: ...

    # inbox
    def add_inbox(self, *, recipient_kind: str, recipient_value: str | None, type: str, title: str, body: str = "",
                link: str | None = None, event_id: str | None = None) -> bool: ...
    def inbox_for(self, user_oid: str, steward_departments: list[str], is_admin: bool, unread_only: bool = False) -> list[dict[str, Any]]: ...
    def mark_inbox_read(self, inbox_id: int) -> None: ...
    def add_feedback(self, answer_id: str, user_oid: str, rating: int, comment: str | None = None) -> None: ...

    # uploads
    def create_upload(self, *, department: str, mode: str, dossier_id: str | None, uploaded_by_oid: str, uploaded_by_name: str,
                    files: list[dict[str, Any]], block_bytes: int) -> str: ...
    def get_upload(self, upload_id: str) -> dict[str, Any]: ...
    def set_upload_status(self, upload_id: str, status: str, reject_reason: str | None = None) -> None: ...
    def touch_upload(self, upload_id: str) -> None: ...
    def bump_scan_attempt(self, upload_id: str) -> int: ...
    def latest_revision(self, dossier_id: str) -> int: ...
    def add_upload_dossier(self, upload_id: str, dossier_id: str, revision: int, manifest_hash: str) -> None: ...
    def upload_dossiers(self, upload_id: str) -> list[dict[str, Any]]: ...
    def mark_intake_sent(self, upload_id: str, dossier_id: str) -> None: ...
    def next_unfiled_seq(self) -> int: ...
    def expire_uploads(self, older_than_days: int) -> list[str]: ...

    # watchdog
    def stuck_pages(self, older_than_minutes: int, limit: int = 200) -> list[dict[str, Any]]: ...
    def bump_page_resend(self, dossier_id: str, revision: int, page_no: int) -> int: ...
    def pending_outbox(self, limit: int = 100) -> list[OutboxRow]: ...
    def mark_outbox_sent(self, row_id: int) -> None: ...


class OpsStore(ReviewOps, Protocol):
    """The `ops` tables (docai.db.tables) and the atomic state changes on them. PostgreSQL everywhere: SqlOps is the only adapter."""

    # registry
    def add_department(self, code: str, name: str) -> None: ...
    def add_access_group(self, group_id: str, department: str, kind: str, name: str) -> None: ...
    def registered_groups(self) -> dict[str, tuple[str, str]]: ...

    # intake
    def register_dossier(self, *, dossier_id: str, department: str, manifest_path: str, manifest_hash: str, files: list[dict[str, Any]],
                        source: str = "upload", from_revision: int | None = None, upload_id: str | None = None,
                        segmentation: str = "auto", expected_pages: int | None = None) -> RegisterResult: ...
    def get_dossier(self, dossier_id: str, revision: int) -> Dossier: ...
    def list_files(self, dossier_id: str, revision: int) -> list[FileRow]: ...
    def finish_file(self, dossier_id: str, revision: int, name: str, status: str, *, pages: int | None = None,
                    converted_to: str | None = None, reason: str | None = None) -> int | None: ...
    def set_dossier_status(self, dossier_id: str, revision: int, status: str, reason: str | None = None) -> None: ...

    # pages
    def register_pages(self, dossier_id: str, revision: int, pages: list[dict[str, Any]]) -> tuple[int, int] | None: ...
    def get_page(self, dossier_id: str, revision: int, page_no: int) -> PageRow: ...
    def list_pages(self, dossier_id: str, revision: int) -> list[PageRow]: ...
    def set_page_status(self, dossier_id: str, revision: int, page_no: int, status: str, *, flagged_lines: int | None = None) -> None: ...
    def finish_page(self, dossier_id: str, revision: int, page_no: int, new_status: str, reason: str | None = None) -> tuple[int, int] | None: ...

    # review tasks and documents
    def create_review_task(self, *, department: str, dossier_id: str, revision: int, page_no: int, line_id: str,
                        line_key: str, reason: str = "readers_disagree", suggested_text: str | None = None, hint_id: str | None = None) -> int: ...
    def list_tasks(self, department: str | None = None, status: str | None = None) -> list[dict[str, Any]]: ...
    def register_documents(self, dossier_id: str, revision: int, documents: list[dict[str, Any]]) -> int: ...
    def list_documents(self, dossier_id: str, revision: int) -> list[DocumentRow]: ...
    def get_document(self, document_id: str) -> DocumentRow: ...
    def set_document_metadata(self, document_id: str, meta: dict[str, Any]) -> None: ...
    def mark_indexed(self, document_id: str, version: int) -> bool: ...
    def try_complete_dossier(self, dossier_id: str, revision: int) -> str: ...
    def dossier_acl(self, dossier_id: str) -> list[str]: ...
    def list_dossiers(self, status: str | None = None, department: str | None = None, limit: int = 100) -> list[dict[str, Any]]: ...
